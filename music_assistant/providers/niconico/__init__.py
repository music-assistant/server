    async def get_artist_toptracks(self, prov_artist_id: str) -> list[Track]:
        """Get a list of most popular tracks for the given artist."""
        all_tracks = []
        page = 0
        while True:
            user_video_data = await call_with_throttler(
                self.niconico_py_client.user.get_user_videos,
                prov_artist_id,
                page=page,
                page_size=500,
            )
            if not user_video_data or not user_video_data.items:
                break

            for item in user_video_data.items:
                track = _parse_track_by_essential_video(self, item.essential)
                all_tracks.append(track)

            page += 1
        return all_tracks

