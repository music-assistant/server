    async def handle_async_init(self) -> None:
        """Handle async initialization of the provider."""
        await self.try_logout()
        self.niconico_py_client = NicoNico()
        await self.try_login()
        # Schedule periodic re-login to refresh the session
        self.mass.create_task(self._schedule_periodic_relogin())

    async def _schedule_periodic_relogin(self) -> None:
        """Periodically re-login to refresh the session."""
        while True:
            await asyncio.sleep(30 * 24 * 60 * 60)  # Wait for 30 days
            self.logger.info("Performing periodic re-login to refresh the session.")
            await self.try_logout()
            await self.try_login()

    async def unload(self, is_removed: bool = False) -> None:
        """
        Handle unload/close of the provider.

        Called when provider is deregistered (e.g. MA exiting or config reloading).
        is_removed will be set to True when the provider is removed from the configuration.
        """
        await self.try_logout()

    @property
    def is_streaming_provider(self) -> bool:
        """
        Return True if the provider is a streaming provider.

        This literally means that the catalog is not the same as the library contents.
        For local based providers (files, plex), the catalog is the same as the library content.
        It also means that data is if this provider is NOT a streaming provider,
        data cross instances is unique, the catalog and library differs per instance.

        Setting this to True will only query one instance of the provider for search and lookups.
        Setting this to False will query all instances of this provider for search and lookups.
        """
        # For streaming providers return True here but for local file based providers return False.
        return True

    async def search(
        self,
        search_query: str,
        media_types: list[MediaType],
        limit: int = 5,
    ) -> SearchResults:
        """Perform search on musicprovider.

        :param search_query: Search query.
        :param media_types: A list of media_types to include.
        :param limit: Number of items to return in the search (per type).
        """
        search_result = SearchResults()

        if MediaType.TRACK in media_types:
            await self.search_videos_by_keyword(search_query, limit, search_result)

        if MediaType.PLAYLIST in media_types:
            await self.search_playlists_by_keyword(search_query, limit, search_result)

        return search_result

    async def search_playlists_by_keyword(
        self, search_query: str, limit: int, search_result: SearchResults
    ) -> None:
        """Search for playlists by keyword."""
        mylist_search_data = await call_with_throttler(
            self.niconico_py_client.video.search.search_lists,
            search_query,
            page_size=limit,
            types=["mylist"],
        )
        if mylist_search_data:
            search_result.playlists = []
            item: EssentialMylist | EssentialSeries
            for item in mylist_search_data.items:
                if isinstance(item, EssentialMylist):
                    search_result.playlists.append(_parse_playlist_by_mylist(self, item))

    async def search_videos_by_keyword(
        self, search_query: str, limit: int, search_result: SearchResults
    ) -> None:
        """Search for videos by keyword."""
        video_search_data = await call_with_throttler(
            self.niconico_py_client.video.search.search_videos_by_keyword,
            search_query,
            page_size=limit,
        )
        if video_search_data:
            search_result.tracks = []
            for item in video_search_data.items:
                if isinstance(item, EssentialVideo):
                    track = _parse_track_by_essential_video(self, item)
                    if track:
                        search_result.tracks.append(track)

    async def get_library_artists(self) -> AsyncGenerator[Artist, None]:
        """Retrieve library artists from the provider."""
        library_item_ids = await self.mass.cache.get(
            "track",
            category=CACHE_CATEGORY_LIBRARY_ITEMS,
            base_key=self.instance_id,
        )
        if not library_item_ids:
            return

        library_item_ids = cast("list[int]", library_item_ids)
        query = "tracks.item_id in :ids"
        query_params = {"ids": library_item_ids}
        tracks = await self.mass.music.tracks.library_items(
            extra_query=query, extra_query_params=query_params
        )

        for track in tracks:
            for artist in track.artists:
                if isinstance(artist, Artist):
                    yield artist

