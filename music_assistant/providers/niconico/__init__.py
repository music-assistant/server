    async def get_stream_details(self, item_id: str, media_type: MediaType) -> StreamDetails:
        """Get stream details (streaming URL and format) for given item."""
        stream_format = await self._get_stream_format(item_id=item_id)
        self.logger.debug(
            "Found stream_format: %s for song %s", stream_format["audio_ext"], item_id
        )

        extra_args = [
            "-user_agent",
            stream_format["user_agent"],
            "-referer",
            "https://www.nicovideo.jp/",
            "-headers",
            "Cookie: " + stream_format["cookies"] + "\r\n",
        ]

        stream_details = StreamDetails(
            provider=self.instance_id,
            item_id=item_id,
            audio_format=AudioFormat(
                content_type=ContentType.try_parse(stream_format["audio_ext"]),
            ),
            stream_type=StreamType.HTTP,
            path=stream_format["url"],
            extra_input_args=extra_args,
            allow_seek=True,
            can_seek=True,
            enable_cache=False,
        )

        if (
            stream_format.get("audio_channels")
            and str(stream_format.get("audio_channels")).isdigit()
        ):
            stream_details.audio_format.channels = int(stream_format.get("audio_channels") or 0)
        if stream_format.get("asr"):
            stream_details.audio_format.sample_rate = int(stream_format.get("asr") or 0)
        return stream_details

